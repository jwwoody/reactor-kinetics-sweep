"""Benchmark the parallel sweep runner: wall time and speedup versus worker count.

Runs a sweep config at 1, 2, 4, 8 and all workers (each into a fresh temporary directory)
and prints a Markdown table. With one worker the runs execute in-process (no pool), so the
speedup is relative to the plain serial loop. Pool start-up (spawned worker processes that
each import NumPy/SciPy) and result transfer are included, which is why the speedup is
less than linear.

Usage::

    python benchmarks/parallel.py [configs/full.toml] [--repeats 1]
"""

from __future__ import annotations

import argparse
import datetime as dt
import os
import platform
import tempfile
from pathlib import Path

import numpy as np
import scipy

from rksweep.sweep import design_points, load_config, run_sweep


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("config", nargs="?", default="configs/full.toml")
    parser.add_argument("--repeats", type=int, default=1, help="best of N per worker count")
    args = parser.parse_args()

    cfg = load_config(args.config)
    cores = os.cpu_count() or 1
    counts = sorted({1, 2, 4, 8, cores})
    times: dict[int, float] = {}
    with tempfile.TemporaryDirectory(prefix="rksweep-bench-") as tmp:
        for workers in counts:
            best = float("inf")
            for rep in range(args.repeats):
                out = Path(tmp) / f"w{workers}-{rep}"
                report = run_sweep(cfg, out, max_workers=workers, progress=False)
                assert report.n_failed == 0, report.failed
                best = min(best, report.wall_s)
            times[workers] = best

    base = times[1]
    print("<!-- generated by benchmarks/parallel.py -->")
    print(
        f"Sweep `{cfg.name}`: {len(design_points(cfg))} runs, Python {platform.python_version()}, "
        f"NumPy {np.__version__}, SciPy {scipy.__version__}, {platform.system()} "
        f"{platform.machine()}, {cores} cores, {dt.date.today().isoformat()}. "
        f"Best of {args.repeats}; wall time includes pool start-up and writing results."
    )
    print()
    print("| Workers | Wall time (s) | Speedup | Efficiency |")
    print("|---:|---:|---:|---:|")
    for workers in counts:
        speedup = base / times[workers]
        print(f"| {workers} | {times[workers]:.2f} | {speedup:.2f}x | {speedup / workers:.0%} |")


if __name__ == "__main__":
    main()
